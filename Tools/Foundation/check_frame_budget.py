"""Check a packaged capture against the sandbox frame budget and retain outliers."""
import argparse
import csv
import json
import math
import statistics
from pathlib import Path

csv.field_size_limit(16 * 1024 * 1024)

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("captures", type=Path, help="captures.json generated by profile_sandbox.ps1")
parser.add_argument("--budget-ms", type=float, default=12.0)
parser.add_argument("--warmup-frames", type=int, default=120)
parser.add_argument("--output", type=Path, required=True)
args = parser.parse_args()
if not math.isfinite(args.budget_ms) or args.budget_ms <= 0 or args.warmup_frames < 0:
    parser.error("Expected a positive time budget and a nonnegative warmup count.")

report = []
for capture in json.loads(args.captures.read_text(encoding="utf-8-sig")):
    with Path(capture["FrameCapture"]).open(encoding="utf-8-sig", newline="") as handle:
        frames = []
        free_ram = []
        for row in csv.DictReader(handle):
            raw = row["FrameTime"]
            if raw is None or raw == "FrameTime" or not raw.strip():
                continue
            try:
                value = float(raw)
            except ValueError:
                continue  # Unreal appends metadata records after the frame data.
            if value > 0 and math.isfinite(value):
                frames.append(value)
                if len(frames) > args.warmup_frames and row.get("MemoryFreeMB"):
                    free_ram.append(float(row["MemoryFreeMB"]))
    measured = sorted(frames[args.warmup_frames:])
    if len(measured) < 100:
        raise ValueError(f"Insufficient frame data in {capture['FrameCapture']}")
    p95 = measured[math.ceil(.95 * len(measured)) - 1]
    report.append(dict(width=capture["Width"], height=capture["Height"], frames=len(measured),
                       median_ms=statistics.median(measured), p95_ms=p95, worst_ms=measured[-1],
                       frames_over_budget=sum(value > args.budget_ms for value in measured),
                       peak_working_set_mib=capture["PeakSampledWorkingSetMiB"],
                       minimum_reported_free_ram_mb=min(free_ram, default=None),
                       minimum_sampled_free_vram_mib=capture.get("MinimumSampledFreeVramMiB"),
                       p95_within_budget=p95 <= args.budget_ms, source=capture["FrameCapture"]))
passed = {(row["width"], row["height"]) for row in report} == {(1280, 720), (1920, 1080)} and all(
    row["p95_within_budget"] for row in report)
args.output.write_text(json.dumps(dict(budget_ms=args.budget_ms, warmup_frames=args.warmup_frames,
                                       passed=passed, captures=report), indent=2), encoding="utf-8")
raise SystemExit(0 if passed else 1)
